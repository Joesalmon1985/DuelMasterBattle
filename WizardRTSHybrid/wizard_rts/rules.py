"""OpenRA actor and weapon rules, loaded from data/openra_rules.json.

The JSON is generated by scripts/import_openra_rules.py from the pinned OpenRA
checkout (MiniYaml with Inherits resolved). HP and damage keep OpenRA's
internal scale (50 HP is 5000). One OpenRA tick is 40 ms (25 ticks per second).

Widelands soldiers are not OpenRA actors. Their entry below is hybrid-defined
from data/tribes/workers/barbarians/soldier/init.lua (health base 13000, attack
1200-1600) so a Widelands soldier can fight OpenRA units and buildings.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

DATA = Path(__file__).resolve().parent / "data" / "openra_rules.json"
TICK_MS = 40

HYBRID_ACTORS: dict[str, dict[str, Any]] = {
    "wl_soldier": {
        "name": "Soldier", "hp": 13000, "armor": "None", "speed": 54, "cost": 0, "queue": "", "prerequisites": "",
        "armaments": ["WL_Axe"], "target_types": ["Ground"], "mobile": True, "is_building": False, "locomotor": "foot",
    },
}
HYBRID_WEAPONS: dict[str, dict[str, Any]] = {
    "WL_Axe": {
        "range": 1.5, "min_range": 0.0, "reload": 25, "burst": 1, "burst_delay": 5, "projectile": "InstantHit",
        "projectile_speed": 0, "valid_targets": ["Ground", "GroundActor"], "invalid_targets": [],
        "warheads": [{"type": "SpreadDamage", "damage": 1400, "spread": 0.0, "versus": {}, "valid_targets": ["GroundActor"]}],
    },
}


@lru_cache(maxsize=1)
def _load() -> dict[str, Any]:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    data["actors"].update(HYBRID_ACTORS)
    data["weapons"].update(HYBRID_WEAPONS)
    return data


def actor(definition: str) -> dict[str, Any] | None:
    """Rules for a hybrid definition such as 'openra.3tnk' or 'widelands.soldier'."""
    key = definition.split(".", 1)[-1].lower()
    if definition == "widelands.soldier":
        key = "wl_soldier"
    return _load()["actors"].get(key)


def weapon(name: str) -> dict[str, Any] | None:
    return _load()["weapons"].get(name)


def ms_per_cell(speed: int) -> int:
    """OpenRA Mobile.Speed is world units per tick; a cell is 1024 units."""
    return max(50, int(1024 / max(speed, 1) * TICK_MS))


def reload_ms(w: dict[str, Any]) -> int:
    return max(100, int(w["reload"]) * TICK_MS)
