#!/usr/bin/env python3
"""Entity evidence catalogue (V4 P0): which passing tests name each entity.

    python3 -m pytest WizardRTSHybrid/tests -q -n 2 -p no:cacheprovider --junitxml=/tmp/junit.xml
    python3 WizardRTSHybrid/scripts/entity_evidence.py /tmp/junit.xml --out docs/ENTITY_EVIDENCE

Levels, from evidence only (nothing is claimed that no passing test names):
  L1  the entity is on a card (content graph);
  L2  a passing test whose id names the entity (the data-driven sweeps parametrize on entity names: every crafter, assembler plan, new OpenRA
      building/unit, new Widelands site, ...);
  L3  two or more such tests.
A name matches a test id as a whole token (case-insensitive, `-`, `_` and `:` folded), so `tank` does not match `tank_assembler`.
Entities with no passing test are listed first in the report: they are the unproven ones.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HYB))

from wizard_rts.content import graph  # noqa: E402


def tokens(s: str) -> str:
    return " " + re.sub(r"[^a-z0-9]+", " ", s.lower()) + " "


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("junit")
    ap.add_argument("--out", default=str(HYB.parent / "docs" / "ENTITY_EVIDENCE"))
    a = ap.parse_args()
    passed = []
    for tc in ET.parse(a.junit).getroot().iter("testcase"):
        if tc.find("failure") is None and tc.find("error") is None and tc.find("skipped") is None:
            passed.append((tc.get("classname", "") + "::" + tc.get("name", "")).split(".")[-1])
    toks = [(p, tokens(p)) for p in passed]
    on_card = {e for c in graph.generated_cards().values() for e in c["entities"]}
    rows = []
    for eid, e in sorted(graph.entities().items()):
        short = eid.split(":", 1)[-1]
        if e["game"] == "widelands":
            short = short.split("_", 1)[-1] if short.split("_", 1)[0] in ("barbarians", "empire", "atlanteans", "frisians", "amazons") else short
        needles = {tokens(short), tokens(eid)}
        hits = sorted({p for p, t in toks if any(n in t for n in needles)})
        level = 3 if len(hits) >= 2 else 2 if hits else 1 if eid in on_card else 0
        rows.append({"id": eid, "game": e["game"], "type": e["type"], "level": level, "tests": hits[:5], "tests_n": len(hits)})
    Path(a.out + ".json").write_text(json.dumps(rows, indent=1))
    by = {}
    for r in rows:
        by.setdefault((r["game"], r["type"]), [0, 0, 0, 0])[r["level"]] += 1
    lines = ["# Entity evidence (generated by scripts/entity_evidence.py)", "", "L1 on a card, L2 named by a passing test, L3 named by two or more. L0 is on no card.", "",
             "| group | L0 | L1 only | L2 | L3 |", "| --- | ---: | ---: | ---: | ---: |"]
    for (g, t), c in sorted(by.items()):
        lines.append(f"| {g} {t} | {c[0]} | {c[1]} | {c[2]} | {c[3]} |")
    unproven = [r for r in rows if r["level"] < 2]
    lines += ["", f"## No passing test names these ({len(unproven)})", ""] + [f"- `{r['id']}` ({r['game']} {r['type']})" for r in unproven]
    Path(a.out + ".md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} entities; unproven {len(unproven)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
