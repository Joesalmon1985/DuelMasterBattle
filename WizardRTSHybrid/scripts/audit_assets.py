"""Asset contract audit (plan v2 8.1): what the sources declare versus what is imported, as numbers.

    python3 scripts/audit_assets.py [--write]    (--write puts the table in docs/evidence/assets/contract_audit.md)
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
ART = HYB.parent / "godot_project" / "client" / "hybrid" / "art" / "catalogue.json"
DATA = HYB / "wizard_rts" / "data"


def main() -> int:
    cat = {i["id"]: i for i in json.loads(ART.read_text(encoding="utf-8"))["items"]}
    wl = json.loads((DATA / "widelands_defs.json").read_text())
    ra = json.loads((DATA / "openra_rules.json").read_text())
    md = json.loads((DATA / "mindustry_defs.json").read_text())
    rows = []
    # Widelands buildings: runnable ones, declared animations
    run = {n: b for n, b in wl["buildings"].items() if b.get("runnable")}
    for state in ("idle", "working", "build", "unoccupied", "empty"):
        declared = [n for n, b in run.items() if state in b["animations"] or state in b["spritesheets"]]
        have = [n for n in declared if (f"widelands.{n}" if state == "idle" else f"widelands.{n}.{state}") in cat]
        rows.append((f"Widelands runnable buildings: `{state}`", len(declared), len(have), "declared in Lua; sheets exist only where the package has image files"))
    # workers: walk directions
    roles = {r for b in run.values() for r in b["working_positions"] if r in wl["workers"]}
    walk = [r for r in roles if all(f"widelands.{r}_worker.walk.{d}" in cat for d in ("e", "ne", "nw", "se", "sw", "w"))]
    rows.append(("Widelands workers of runnable buildings: walk in 6 directions", len(roles), len(walk), "walk sheets per direction"))
    # OpenRA roster (non-building units)
    units = [a for a, r in ra["actors"].items() if not r.get("is_building") and r.get("queue") in ("Infantry", "Vehicle", "Ship", "Aircraft")]
    have = [a for a in units if cat.get(f"openra.{a}", {}).get("status") == "imported"]
    rows.append(("OpenRA units (Infantry, Vehicle, Ship, Aircraft queues)", len(units), len(have), "imported (frames per facing; turret composited, not independent)"))
    alias = [a for a in units if cat.get(f"openra.{a}", {}).get("status") == "alias_placeholder"]
    rows.append(("OpenRA units drawn by an alias placeholder", len(units), len(alias), "must be 0 for a card that can be dealt"))
    bld = [a for a, r in ra["actors"].items() if r.get("is_building") and r.get("queue") in ("Building", "Defense")]
    rows.append(("OpenRA buildings and defences with art", len(bld), sum(1 for a in bld if f"openra.{a}" in cat), "idle (+ damaged) frames; no construction (`make`) sequences yet"))
    # Mindustry
    mb = [b for b in md["blocks"]]
    rows.append(("Mindustry blocks with a picture", len(mb), sum(1 for b in mb if f"mindustry.block.{b.replace('-', '_')}" in cat), "single composited image; no drawer layers"))
    mu = list(md["units"])
    rows.append(("Mindustry units with a picture", len(mu), sum(1 for u in mu if f"mindustry.unit.{u.replace('-', '_')}" in cat), "single composited image; no independent weapons"))
    lines = ["# Asset contract audit (generated by scripts/audit_assets.py)\n", "| contract item | declared | imported | note |", "| --- | ---: | ---: | --- |"]
    for label, d, h, note in rows:
        lines.append(f"| {label} | {d} | {h} | {note} |")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in sys.argv:
        out = HYB / "docs" / "evidence" / "assets" / "contract_audit.md"
        out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
