#!/usr/bin/env python3
"""docs/COVERAGE.md from docs/feature_catalogue.json: imported vs simulated vs tested vs headed-verified vs AI-usable, per game and category.

Definitions (one row per catalogue item): imported = discovered in the pinned source tree; simulated = status adapted or higher (the
data runs in the hybrid); tested = status tested or verified (a named test exercises the behaviour); headed-verified = status verified
(a headed Godot script shows it on screen); AI-usable = the faction AI builds or uses it. Importing data never raises a row above `missing`.
"""
import json
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
cat = json.loads((HYB / "docs" / "feature_catalogue.json").read_text())
rows = {}
for it in cat["items"]:
    key = f"{it['game']}.{it['category']}"
    r = rows.setdefault(key, {"imported": 0, "simulated": 0, "tested": 0, "headed_verified": 0, "ai_usable": 0})
    r["imported"] += 1
    st = it["status"]
    r["simulated"] += st in ("adapted", "integrated", "tested", "verified")
    r["tested"] += st in ("tested", "verified")
    r["headed_verified"] += st == "verified"
    r["ai_usable"] += bool(it.get("ai_usable"))
lines = ["# Coverage (generated by `scripts/make_coverage.py`; do not edit)", "",
         "Source: `docs/feature_catalogue.json` (`scripts/build_catalogue.py`) and the hand-kept evidence map `docs/feature_status.json`. "
         "A definition that is merely imported counts only in the first column. Nothing here is a claim about the whole of Widelands, OpenRA or Mindustry.", "",
         "| Game / category | Imported | Simulated | Tested | Headed-verified | AI-usable | Tested share |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
for k in sorted(rows):
    r = rows[k]
    lines.append(f"| {k} | {r['imported']} | {r['simulated']} | {r['tested']} | {r['headed_verified']} | {r['ai_usable']} | {100 * r['tested'] / max(r['imported'], 1):.0f}% |")
tot = {c: sum(r[c] for r in rows.values()) for c in ("imported", "simulated", "tested", "headed_verified", "ai_usable")}
lines.append(f"| **all** | {tot['imported']} | {tot['simulated']} | {tot['tested']} | {tot['headed_verified']} | {tot['ai_usable']} | {100 * tot['tested'] / max(tot['imported'], 1):.0f}% |")
(HYB / "docs" / "COVERAGE.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
