"""Write docs/NEURO_OBS_SCHEMA.md from neuro/schema.py: the definitive observation schema, for M3 and for review.

    py -3 scripts/dump_obs_schema.py            # write the document
    py -3 scripts/dump_obs_schema.py --check    # exit 1 when the committed document is stale (tests/test_neuro_features.py runs this)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HYB))
sys.path.insert(0, str(HYB.parent))

from neuro import features as F  # noqa: E402
from neuro import schema as S  # noqa: E402

OUT = HYB.parent / "docs" / "NEURO_OBS_SCHEMA.md"


def render() -> str:
    lines = [
        "# Neural observation schema (generated; do not edit by hand)",
        "",
        "Generated by `WizardRTSHybrid/scripts/dump_obs_schema.py` from `WizardRTSHybrid/neuro/schema.py`; `tests/test_neuro_features.py` fails when this file is stale.",
        "",
        f"* Schema version: `{S.OBS_SCHEMA_VERSION}`",
        f"* Schema hash (schema + frozen roster): `{F.obs_schema_hash()}`",
        f"* Kind embedding: {F.n_kinds()} rows x {S.EMB_DIM} (row 0 unknown; rows 1-582 the frozen roster in manifest order; rows 583-585: `warehouse`, `blight_nest`, `unit:soldier`)",
        f"* Kind static features: {S.N_STATIC} columns: `{', '.join(S.KIND_STATIC_COLUMNS)}`",
        f"* Unit static features (H3): {len(S.UNIT_STATIC_COLUMNS)} columns: `{', '.join(S.UNIT_STATIC_COLUMNS)}`",
        f"* Key wares ({len(S.KEY_WARES)}): `{', '.join(S.KEY_WARES)}`",
        f"* Ware groups ({S.N_GROUPS}): `{', '.join(S.GROUP_NAMES)}`",
        f"* Context {S.CTX_DIM}, priorities {S.PRIO_DIM}, memory {S.MEM_DIM}",
        "",
        "## Network inputs (declared width = sum of the parts, in this order)",
        "",
        "| Network | Width | Parts (name: width, source) |",
        "| --- | ---: | --- |",
    ]
    for name, parts in S.NET_INPUTS.items():
        lines.append(f"| {name} | {S.DIMS[name]} | " + "; ".join(f"{p}: {w} ({src})" for p, w, src in parts) + " |")
    lines += ["", "Sources: `raw` is filled by `neuro/observer.py`; `emb` is the learned kind embedding; `net:X` is an output of network X supplied by the controller; `ctx`, `prio`, `mem` come from the faction coordinator.", "",
              "## Raw feature fields", ""]
    for name, fields in S.RAW_NAMES.items():
        lines += [f"### {name} raw ({len(fields)})", "", ", ".join(f"`{f}`" for f in fields), ""]
    lines += [f"### N8card raw ({S.N_CARD})", "", "the 28 card features of `learn/draft_module.card_features`, then " + ", ".join(f"`{f}`" for f in S.CARD_FLAGS), ""]
    for name, fields in S.HEAD_RAW.items():
        lines += [f"### {name} candidate raw ({len(fields)})", "", ", ".join(f"`{f}`" for f in fields) if fields else "(none: all inputs are network outputs)", ""]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        old = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.is_file() else ""
        return 0 if old == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
