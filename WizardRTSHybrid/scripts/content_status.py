"""Content status (plan v2 15.1): every imported entity as functional, pending (with the blocker) or excluded (with the reason).

    python3 scripts/content_status.py [--write]    (--write puts the table in docs/evidence/content_status.md)
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HYB))
sys.path.insert(0, str(HYB.parent))

from wizard_rts import construction as con  # noqa: E402
from wizard_rts.industry import registry as mdy  # noqa: E402

DATA = HYB / "wizard_rts" / "data"
EXCLUDED_RA_BUILDINGS = {"powr": "power generation (roster rule 4.2)", "apwr": "power generation", "fpwr": "power generation", "fapw": "power generation",
                         "proc": "resource extraction (refinery)", "silo": "resource storage", "procf": "resource extraction"}


def main() -> int:
    wl = json.loads((DATA / "widelands_defs.json").read_text())
    ra = json.loads((DATA / "openra_rules.json").read_text())
    md = json.loads((DATA / "mindustry_defs.json").read_text())
    rows: list[tuple[str, str, int, str]] = []
    menu = con.full_menu()
    wlb = collections.Counter()
    for n, b in wl["buildings"].items():
        if f"wl:{n}" in menu:
            wlb["functional"] += 1
        elif b["type"] in ("militarysite", "trainingsite"):
            wlb["excluded"] += 1
        else:
            wlb["pending"] += 1
    for k, why in (("functional", "runnable production site in the menu (153 incl. five tribes)"), ("excluded", "Widelands military and training sites: out of the Prehistoric civilian roster (D05)"),
                   ("pending", "warehouses and ports, markets, and production sites with commands the interpreter does not run")):
        rows.append(("Widelands buildings", k, wlb[k], why))
    units = {a for a, r in ra["actors"].items() if not r.get("is_building") and r.get("queue") in ("Infantry", "Vehicle", "Ship", "Aircraft")}
    have = {r["definition"].split(".", 1)[1] for rs in con.RECIPES.values() for r in rs.values() if str(r.get("definition", "")).startswith("openra.")}
    rows.append(("OpenRA units (RA)", "functional", len(units & have), "recipe, producer building and card"))
    rows.append(("OpenRA units (RA)", "excluded", len(units & {"harv", "ant", "zombie", "fireant", "scoutant", "warriorant"}), "harvester (credit economy replaced) and mission-only creatures"))
    rows.append(("OpenRA units (RA)", "pending", len(units - have - {"harv", "ant", "zombie", "fireant", "scoutant", "warriorant"}),
                 "aircraft mechanics, transports, capture/repair/support-power units"))
    bld = {a for a, r in ra["actors"].items() if r.get("is_building") and r.get("queue") in ("Building", "Defense")}
    fn = {"barr", "weap", "fact", "pbox", "ftur", "tsla", "gun", "spen", "syrd"}
    rows.append(("OpenRA buildings (RA)", "functional", len(bld & fn), "barracks, war factory, naval yards and the defences in `construction.BUILD_MENU`"))
    rows.append(("OpenRA buildings (RA)", "excluded", len(bld & set(EXCLUDED_RA_BUILDINGS)), "power and resource extraction (roster rule 4.2)"))
    rows.append(("OpenRA buildings (RA)", "pending", len(bld - fn - set(EXCLUDED_RA_BUILDINGS)), "tech, radar, support powers, walls, helipads, forward-base duplicates"))
    rows.append(("Mindustry blocks", "functional", len(mdy.kinds()), "drill, belt, power, smelter, press, factory slice (`wizard_rts/industry`)"))
    rows.append(("Mindustry blocks", "pending", len(md["blocks"]) - len(mdy.kinds()), "parsed from Blocks.java; liquids, heat, payload, logic, Erekir, turrets, large walls not simulated"))
    rows.append(("Mindustry units", "functional", 3, "dagger, crawler, nova from the ground factory"))
    rows.append(("Mindustry units", "pending", len(md["units"]) - 3, "T2-T5 need payload reconstructors; naval, air, legged, Erekir"))
    lines = ["# Content status (generated by scripts/content_status.py)\n", "| source | status | entities | meaning |", "| --- | --- | ---: | --- |"]
    for src, st, n, why in rows:
        lines.append(f"| {src} | {st} | {n} | {why} |")
    lines.append("\nDev-only sandbox blocks (item/liquid/power sources and voids) are not separated yet; they are inside Mindustry `pending`.\n")
    text = "\n".join(lines) + "\n"
    print(text)
    if "--write" in sys.argv:
        (HYB / "docs" / "evidence" / "content_status.md").write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
