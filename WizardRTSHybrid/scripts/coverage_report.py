"""Write the content coverage table (wizard_rts.coverage) to docs/evidence/coverage/ as CSV and markdown.

    python3 scripts/coverage_report.py          # write and print the summary
    python3 scripts/coverage_report.py --check  # exit 1 when the committed csv is stale
"""
from __future__ import annotations

import csv
import io
import sys
from pathlib import Path

HYB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HYB))
sys.path.insert(0, str(HYB.parent))

from wizard_rts import coverage  # noqa: E402

OUT = HYB / "docs" / "evidence" / "coverage"
COLS = ["key", "game", "type", "name", "tribe", "status", "blocker", "entity", "era", "card", "art"]


def main() -> int:
    rows = coverage.build()
    buf = io.StringIO()
    w = csv.DictWriter(buf, COLS, extrasaction="ignore", lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    md = ["# Content coverage (generated by scripts/coverage_report.py)\n", "| group | functional | pending | excluded |", "| --- | ---: | ---: | ---: |"]
    for k, v in sorted(coverage.summary(rows).items()):
        md.append(f"| {k} | {v['functional']} | {v['pending']} | {v['excluded']} |")
    art: dict[str, int] = {}
    for r in rows:
        if r["status"] == "functional":
            art[r["art"]] = art.get(r["art"], 0) + 1
    md.append("\nArt level of functional entities: " + ", ".join(f"{k} {v}" for k, v in sorted(art.items())) + "\n")
    text = "\n".join(md)
    if "--check" in sys.argv:
        old = (OUT / "coverage.csv").read_text(encoding="utf-8") if (OUT / "coverage.csv").is_file() else ""
        return 0 if old == buf.getvalue() else 1
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "coverage.csv").write_text(buf.getvalue(), encoding="utf-8")
    (OUT / "coverage.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
